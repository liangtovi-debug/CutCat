"""Fresh worker-only verification for portable, reusable source selections.

The persisted binding is deliberately not SourceIdentity: paths, inode/file
state, project dimensions/rate and viewer tokens are session facts, not media
content. The sampled hash detects ordinary source replacement, not adversarial
full-file immutability. Verification reads bounded identity samples and stream
headers only; it does not decode a long saved range or relax Apply's proof.
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass
from fractions import Fraction
import hashlib
import json

from .source_ranges import (SourceRangeBinding, range_frames,
                            validate_source_range_binding, validate_source_range)
from .source_viewer import SourceIdentity, SourceViewerError, _check, _current, _identity


# Only interpretation/timing facts enter the portable signature. In particular,
# ffprobe format.filename and free-form tags (including encoder/path tags) do not.
_STREAM_FIELDS = (
    'index', 'codec_type', 'codec_name', 'codec_tag_string', 'profile',
    'width', 'height', 'coded_width', 'coded_height', 'pix_fmt',
    'sample_aspect_ratio', 'display_aspect_ratio', 'color_range', 'color_space',
    'color_transfer', 'color_primaries', 'chroma_location', 'field_order',
    'r_frame_rate', 'avg_frame_rate', 'time_base', 'start_pts', 'start_time',
    'duration_ts', 'duration', 'nb_frames', 'sample_fmt', 'sample_rate',
    'channels', 'channel_layout', 'bits_per_sample', 'bits_per_raw_sample',
    'initial_padding', 'has_b_frames', 'disposition',
)
_RATIONAL_FIELDS = frozenset((
    'sample_aspect_ratio', 'display_aspect_ratio', 'r_frame_rate',
    'avg_frame_rate', 'time_base', 'start_time', 'duration',
))
_SIDE_DATA_FIELDS = ('side_data_type', 'displaymatrix', 'rotation')
_MEDIA_FIELDS = (
    'width', 'height', 'has_video', 'has_audio', 'color_space', 'color_transfer',
    'color_primaries', 'color_range', 'input_encoding',
)


def _rational(value):
    """Canonicalize exact probe decimals/ratios, preserving unknown sentinels."""
    if value in (None, 'N/A', '0/0', '0:0'):
        return value
    fraction = Fraction(str(value).replace(':', '/'))
    return [fraction.numerator, fraction.denominator]


def _semantic_signature(session, info):
    media = session.media
    imported = {key: getattr(media, key) for key in _MEDIA_FIELDS}
    imported.update(
        duration=_rational(media.duration), audio_offset=_rational(media.audio_offset),
        fps=_rational(Fraction(media.fps_num, media.fps_den)),
        decoded_video_end=(None if media.decoded_video_end_num is None else
                           _rational(Fraction(media.decoded_video_end_num,
                                              media.decoded_video_end_den))),
    )
    # Source filenames, synthesis text, license labels, caption IDs and dates
    # are not decoding semantics. Actual generated bytes remain fully checked
    # by _identity, while sample sizing/origin metadata is bound here.
    for field in ('speech_provenance', 'sound_provenance'):
        provenance = getattr(media, field)
        imported[field] = (None if provenance is None else {
            key: getattr(provenance, key)
            for key in ('output_sha256', 'sample_rate', 'sample_count')
        })
    streams = []
    for stream in info['source_streams']:
        entry = {key: (_rational(stream[key]) if key in _RATIONAL_FIELDS else stream[key])
                 for key in _STREAM_FIELDS if key in stream}
        entry['side_data'] = [
            {key: side[key] for key in _SIDE_DATA_FIELDS if key in side}
            for side in stream.get('side_data_list', [])
            if any(key in side for key in _SIDE_DATA_FIELDS)
        ]
        # Older containers represent rotation as a tag rather than side data.
        if 'rotate' in stream.get('tags', {}):
            entry['rotation_tag'] = _rational(stream['tags']['rotate'])
        streams.append(entry)
    source_format = info['source_format']
    payload = {
        'algorithm_version': 1,
        'media': imported,
        'streams': streams,
        'format': {key: (_rational(source_format[key]) if key in _RATIONAL_FIELDS
                         else source_format[key])
                   for key in ('format_name', 'nb_streams', 'start_time', 'duration')
                   if key in source_format},
        'origin': _rational(info['origin']),
        'format_start': _rational(info['format_start']),
    }
    raw = json.dumps(payload, sort_keys=True, separators=(',', ':'),
                     ensure_ascii=True, allow_nan=False).encode('ascii')
    return hashlib.sha256(raw).hexdigest()


@dataclass(frozen=True)
class SourceRangeVerification:
    binding: SourceRangeBinding
    in_frame: int
    out_frame: int
    identity: SourceIdentity
    generation: int
    session_token: str

    def is_current(self, session, project=None):
        """Pure viewer-generation check; owner also guards editor/range tokens."""
        return _current(self, session, project)


def verify_source_range(backend, session, record=None, cancel=None):
    """Check Save (record=None) or Recall without changing marks or project.

    This function belongs on the viewer's existing worker. It shares that
    backend's lock and entire-operation deadline, including lock waiting and
    before/after file checks. No validity result is persisted or cached. A
    recalled binding must match in full; there is no implicit rebind or clamp.
    A successful result is still not a proof for Insert/Overwrite application.
    """
    request = deepcopy(session)
    saved = deepcopy(record)
    deadline = backend._begin(cancel)
    try:
        if saved is not None:
            validate_source_range(saved)
            if saved.media_id != request.media_id:
                raise SourceViewerError('Saved range belongs to another media item.')
        start, end = (request.selection() if saved is None else
                      range_frames(saved, request.fps, request.total_frames))
        identity = _identity(request, cancel, deadline)
        info = backend._probe_source(request, identity, cancel, deadline)
        # Unlike auditions or edit proofs, storing metadata need not decode all
        # selected frames. Header/source bounds still cannot be exceeded.
        if not 0 <= start < end <= min(request.total_frames, info['capacity']):
            raise SourceViewerError('Saved source range exceeds complete source-frame intervals.')
        _check(cancel, deadline)
        binding = SourceRangeBinding(
            algorithm_version=1, file_size=identity.state[0][2],
            sampled_content_sha256=identity.sample_sha256,
            semantic_source_signature=_semantic_signature(request, info),
        )
        validate_source_range_binding(binding)
        if saved is not None and saved.binding != binding:
            raise SourceViewerError('Saved range is unavailable: source content or interpretation changed. Save a new range explicitly.')
        backend._revalidate(request, identity, cancel, deadline)
        return SourceRangeVerification(binding, start, end, identity,
                                       request.generation, request.token)
    except SourceViewerError:
        raise
    except (OSError, ValueError, KeyError, TypeError, IndexError, OverflowError) as exc:
        raise SourceViewerError(f'Cannot verify saved source range: {exc}') from exc
    finally:
        backend._lock.release()
