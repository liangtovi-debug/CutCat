@pytest.fixture(autouse=True)
def release_test_qt_windows():
    """Release per-test native media/widgets before interpreter destruction.

    close() merely hides a QWidget; retaining hundreds of hidden media owners
    makes aggregate teardown depend on Python/Qt destruction order. Keep shared
    pre-existing roots and leave production close/reopen behavior unchanged.
    """
    import sys
    qt = sys.modules.get('PySide6.QtWidgets')
    app = qt.QApplication.instance() if qt else None
    existing = list(app.topLevelWidgets()) if app else []
    yield
    qt = sys.modules.get('PySide6.QtWidgets')
    app = qt.QApplication.instance() if qt else None
    if app:
        from scripts.qt_test_cleanup import cleanup_test_windows
        cleanup_test_windows(app, existing)


def pytest_sessionstart(session):
    from scripts.pytest_numeric_contrast import numeric_contrast_only, verify_numeric_imports
    if numeric_contrast_only(session.config):
        verify_numeric_imports(session.config)
        return
    # Load the verified Windows provider before test modules import Pillow.
    from lumen.caption_runtime import initialize
    initialize()


def pytest_sessionfinish(session, exitstatus):
    from scripts.pytest_numeric_contrast import verify_numeric_imports
    verify_numeric_imports(session.config)
