"""Session-only font provisioning for actual Qt geometry and rendering tests.

Qt's Windows ``offscreen`` plugin can expose no system fonts at all, unlike
the desktop ``windows`` plugin.  In CI, LUMEN_TEST_CJK_FONT_DIR explicitly
points to the already provisioned, hash-verified Noto fixture.  Keep that font
registered for the whole pytest session: removing it between individual tests
can leave later widgets measuring and painting missing-glyph boxes, including
ordinary Latin text.  This is test infrastructure, not an application font
installation, download, bundle, or claim of desktop-plugin validation.
"""
from __future__ import annotations

import importlib.util
import os

import pytest


@pytest.fixture(scope='session', autouse=True)
def qt_test_font(request):
    """Retain a real font across all Qt tests, preserving native UI preference."""
    from scripts.pytest_numeric_contrast import numeric_contrast_only
    if numeric_contrast_only(request.config):
        yield None
        return
    directory = os.environ.get('LUMEN_TEST_CJK_FONT_DIR')
    if directory is None or importlib.util.find_spec('PySide6') is None:
        yield None
        return

    os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
    from PySide6.QtGui import QFont, QFontDatabase, QFontInfo, QTextLayout
    from PySide6.QtWidgets import QApplication
    from scripts.provision_test_font import verify_fixture

    # A configured but invalid fixture is an error, never a silent skip.
    verified = verify_fixture(directory)
    app = QApplication.instance() or QApplication([])
    original_font = QFont(app.font())
    original_info = QFontInfo(original_font)
    font_id = QFontDatabase.addApplicationFont(verified['font_file'])
    assert font_id >= 0, 'Qt could not register the verified session test font'
    families = QFontDatabase.applicationFontFamilies(font_id)
    assert families, 'The verified session test font exposes no Qt family'
    if not original_info.family() or original_info.pixelSize() <= 0:
        # The fontless offscreen backend needs an explicit family.  When an
        # actual native font already works (macOS/Linux/desktop Windows), leave
        # its choice and metrics intact; registration still enables CJK fallback.
        font = QFont(original_font)
        font.setFamilies(list(dict.fromkeys([*families, *font.families()])))
        app.setFont(font)

    # Font-family strings alone do not prove Qt can shape text.  The native
    # Windows failure returned family='', pixels=-1 and painted Latin as tofu.
    layout = QTextLayout('CutCatABCxyz0123456789', app.font())
    layout.beginLayout()
    layout.createLine().setLineWidth(1000)
    layout.endLayout()
    runs = layout.glyphRuns()
    info = QFontInfo(app.font())
    assert info.family() and info.pixelSize() > 0, 'Qt still has no resolved UI font'
    assert runs and all(run.rawFont().isValid() for run in runs)
    assert all(index != 0 for run in runs for index in run.glyphIndexes()), \
        'Session UI font must shape actual Latin glyphs, not missing-glyph boxes'
    try:
        yield {'font_id': font_id, 'families': families,
               'resolved_family': info.family(), 'font_file': verified['font_file']}
    finally:
        app.setFont(original_font)
        QFontDatabase.removeApplicationFont(font_id)


